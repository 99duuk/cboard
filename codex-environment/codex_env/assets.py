"""Canonical local assets and declarative external-source inventory.

Only capture writes files, and only beneath the supplied deployment root.
Authentication files and plugin caches are never copied.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import tomllib
from urllib.parse import urlsplit, urlunsplit

EXCLUDED = {'.git', 'node_modules', '__pycache__', '.DS_Store', '.venv', 'venv',
            '.pytest_cache', '.mypy_cache', '.env', 'auth.json', 'credentials.json'}


def _entries(home: Path):
    agents = home / '.agents'
    if (agents / 'AGENTS.md').exists():
        yield agents / 'AGENTS.md', Path('AGENTS.md')
    for group in ('rules', 'skills'):
        directory = agents / group
        if directory.exists():
            for source in sorted(directory.iterdir()):
                if source.name not in EXCLUDED:
                    yield source, Path(group) / source.name
    roles = home / '.codex/agents'
    if roles.exists():
        for source in sorted(roles.glob('*.toml')):
            yield source, Path('agents') / source.name


def _copy(source: Path, target: Path, boundary: Path, ancestors=frozenset(), ignored=frozenset()):
    resolved = source.resolve(strict=True)
    if not resolved.is_relative_to(boundary):
        raise ValueError(f'External nested asset link requires explicit capture: {source}')
    if resolved in ancestors:
        raise ValueError(f'Cyclic asset link: {source}')
    if resolved.is_dir():
        target.mkdir()
        for child in sorted(resolved.iterdir()):
            if (child.name not in EXCLUDED and not child.name.startswith('.env.')
                    and child not in ignored and not (child.is_dir() and (child / 'pyvenv.cfg').exists())):
                _copy(child, target / child.name, boundary, ancestors | {resolved}, ignored)
        shutil.copystat(resolved, target)
    elif resolved.is_file():
        shutil.copy2(resolved, target)
    else:
        raise ValueError(f'Unsupported asset type: {source}')


def tree_hash(path: Path) -> str:
    """Content/path/executable-bit fingerprint, independent of host or timestamps."""
    digest = hashlib.sha256()
    files = sorted(path.rglob('*')) if path.is_dir() else [path]
    for item in files:
        if item.is_symlink():
            raise ValueError(f'Canonical asset must not contain links: {item}')
        relative = str(item.relative_to(path)) if item != path else '.'
        digest.update(relative.encode() + b'\0')
        digest.update(b'd' if item.is_dir() else b'f')
        digest.update(str(item.stat().st_mode & 0o111).encode() + b'\0')
        if item.is_file():
            digest.update(item.read_bytes())
    return digest.hexdigest()


def _git(path: Path, *args: str) -> str:
    result = subprocess.run(['git', '-C', str(path), *args], capture_output=True,
                            text=True, timeout=10)
    return result.stdout.strip() if result.returncode == 0 else ''


def _safe_url(value: str) -> str:
    if '://' not in value:
        return value
    parsed = urlsplit(value)
    return urlunsplit((parsed.scheme, parsed.hostname or '', parsed.path, '', ''))


def inventory_sources(root: Path, home: Path) -> dict:
    """Inventory allowlisted metadata only; no auth files or arbitrary config export."""
    config_path = home / '.codex/config.toml'
    config = tomllib.loads(config_path.read_text()) if config_path.exists() else {}
    sources = []
    for name, marketplace in sorted(config.get('marketplaces', {}).items()):
        remote = marketplace.get('source_type') == 'git'
        source = _safe_url(marketplace.get('source', '')) if remote else ''
        sources.append({'kind': 'marketplace', 'name': name, 'source': source,
                        'revision': marketplace.get('last_revision', ''),
                        'status': 'reinstallable' if remote else 'provider_or_local_install_required',
                        'install': ['codex', 'plugin', 'marketplace', 'add', source] +
                        (['--ref', marketplace['last_revision']] if marketplace.get('last_revision') else [])
                        if remote else []})
    # Local OMO installation is generated by its provider, not a Git marketplace.
    omo_manifest = home / '.codex/plugins/cache/sisyphuslabs/.agents/plugins/marketplace.json'
    if omo_manifest.exists():
        marketplace_data = json.loads(omo_manifest.read_text())
        for plugin in marketplace_data.get('plugins', []):
            local = plugin.get('source', {}).get('path', '')
            location = (home / '.codex/plugins/cache/sisyphuslabs' / local).resolve()
            boundary = (home / '.codex/plugins/cache/sisyphuslabs').resolve()
            if not location.is_relative_to(boundary):
                raise ValueError('Unsafe local marketplace path')
            metadata = location / 'lazycodex-install.json'
            if metadata.exists():
                package = json.loads(metadata.read_text())
                sources.append({'kind': 'provider_bootstrap', 'name': 'omo@sisyphuslabs',
                                'version': package['version'],
                                'status': 'provider_bootstrap_requires_review',
                                'reason': 'Pinned lazycodex installer delegates to oh-my-openagent@latest; local MCP paths require regeneration',
                                'install': ['npx', '--yes', f"lazycodex-ai@{package['version']}",
                                            'install', '--no-tui', '--no-codex-autonomous']})
    for name, plugin in sorted(config.get('plugins', {}).items()):
        sources.append({'kind': 'plugin', 'name': name, 'enabled': plugin.get('enabled', True),
                        'status': 'provider_managed', 'install': ['codex', 'plugin', 'add', name]})
    rea = home / '.local/share/rea/node_modules/rea-agents/package.json'
    if rea.exists():
        package = json.loads(rea.read_text())
        version = package['version']
        sources.append({'kind': 'npm', 'name': 'rea-agents', 'version': version,
                        'node': package.get('engines', {}).get('node', ''),
                        'status': 'reinstallable',
                        'install': ['npm', 'install', '--prefix', '${HOME}/.local/share/rea', f'rea-agents@{version}']})
    for source, relative in _entries(home):
        if source.is_symlink() and source.is_dir() and not source.resolve().is_relative_to(root.resolve()):
            resolved = source.resolve()
            sources.append({'kind': 'snapshot', 'name': str(relative),
                            'source': _safe_url(_git(resolved, 'remote', 'get-url', 'origin')),
                            'revision': _git(resolved, 'rev-parse', 'HEAD'),
                            'dirty': bool(_git(resolved, 'status', '--porcelain')),
                            'status': 'vendored_working_tree'})
    return {'version': 1, 'sources': sources}


def _manifest(data: dict) -> str:
    lines = ['version = 1', '']
    for source in data['sources']:
        lines.append('[[sources]]')
        for key, value in source.items():
            lines.append(f'{key} = {json.dumps(value, ensure_ascii=False)}' if not isinstance(value, bool)
                         else f'{key} = {str(value).lower()}')
        lines.append('')
    return '\n'.join(lines)


def capture_assets(root: Path, home: Path) -> dict:
    """Capture absent assets atomically; existing canonical edits remain authoritative."""
    root, home = Path(root), Path(home)
    inventory = inventory_sources(root, home)
    captured = []
    for source, relative in _entries(home):
        target = root / 'assets' / relative
        if not target.exists() and not target.is_symlink():
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = Path(tempfile.mkdtemp(prefix='.capture-', dir=target.parent))
            try:
                resolved = source.resolve(strict=True)
                ignored = frozenset()
                if resolved.is_dir() and (resolved / '.git').exists():
                    result = subprocess.run(['git', '-C', str(resolved), 'ls-files', '--others',
                                             '--ignored', '--directory', '--exclude-standard', '-z'],
                                            capture_output=True, text=True, timeout=10, check=True)
                    ignored = frozenset(resolved / value.rstrip('/')
                                        for value in result.stdout.split('\0') if value)
                _copy(source, temporary / 'asset', resolved if resolved.is_dir() else resolved.parent,
                      ignored=ignored)
                os.replace(temporary / 'asset', target)
            finally:
                shutil.rmtree(temporary)
        if target.is_symlink():
            raise ValueError(f'Canonical asset cannot be a symlink: {target}')
        captured.append({'path': str(relative), 'sha256': tree_hash(target)})
    manifest = root / 'sources.toml'
    if not manifest.exists():
        manifest.write_text(_manifest(inventory))
    return {'assets': captured, **inventory}


def asset_links(root: Path, home: Path, accounts) -> list[tuple[Path, Path]]:
    """Return transaction inputs; preserve unrelated ~/.agents entries and account files."""
    root, home = Path(root), Path(home)
    canonical = root / 'assets'
    links = []
    info = root / 'BUNDLE-INFO.json'
    toolkit = info.exists() and json.loads(info.read_text()).get('scope') == 'toolkit'
    if not toolkit and (canonical / 'AGENTS.md').exists():
        links.append((home / '.agents/AGENTS.md', canonical / 'AGENTS.md'))
    for group in ('skills', 'rules'):
        directory = canonical / group
        if not toolkit and directory.exists():
            links.extend((home / '.agents' / group / p.name, p) for p in sorted(directory.iterdir()) if p.name != '.gitkeep')
    values = accounts.values() if isinstance(accounts, dict) else accounts
    for account in values:
        value = account.get('home', account.get('path')) if isinstance(account, dict) else getattr(account, 'home', account)
        text = str(value).replace('${HOME}', str(home))
        account_home = home / text[2:] if text.startswith('~/') else home if text == '~' else Path(text)
        if not account_home.is_absolute():
            account_home = home / account_home
        for name in ('AGENTS.md', 'skills', 'rules'):
            source = canonical / name
            supplied = not toolkit and (source.is_file() or (source.is_dir() and any(p.name != '.gitkeep' for p in source.iterdir())))
            if supplied or (home / '.agents' / name).exists():
                links.append((account_home / name, home / '.agents' / name))
        roles = canonical / 'agents'
        if roles.exists():
            links.extend((account_home / 'agents' / p.name, p) for p in sorted(roles.glob('*.toml')))
    return links
